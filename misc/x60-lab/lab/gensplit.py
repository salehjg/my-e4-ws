"""D3Q19 kernel lab: the direction-split AA kernel, generated with pystencils (docs/notes3 Loop 14).

The hand-written kernel hand/hand-aa.hpp (Loops 4, 7) works on blocks of BY rows of one z-plane in
three passes (moments in groups of GM directions, macroscopic values, collision in groups of GP
opposite-direction pairs), so that only a few memory streams are live at a time. The generator of
those passes lives with the waLBerla app that uses it:
submodules/walberla/apps/benchmarks/SweepgenLbmCPU/lbm_split.py (`SplitAA`). This script emits its
passes (RVV) and its block driver as a lab kernel: `run_kernel_aa` is the lab driver's AA entry.

Usage (laptop, like gen.py):
  PYTHONPATH=submodules/pystencils/src .venv-rvv/bin/python misc/x60-lab/lab/gensplit.py \
      misc/x60-lab/lab/src f32-rvvsplit-by2gm5gp3 f64-rvvsplit-by1gm5gp3+pf=128+nomacro
Variant: <dt>-rvvsplit-by<BY>gm<GM>gp<GP>[+pf=<bytes>][+nomacro]
  pf=D     software prefetch D bytes ahead in every pass (cpu.vectorize.prefetch_distance)
  nomacro  the macroscopic pass does not write the rho/u outputs (plan lever C6)
"""

import pathlib
import re
import sys

import sympy as sp
import pystencils as ps
from lbmpy import LBStencil, Stencil, LBMConfig, Method

REPO = pathlib.Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "submodules/walberla/apps/benchmarks/SweepgenLbmCPU"))
from lbm_split import SplitAA  # noqa: E402

DTYPES = {"f32": ("float32", "float"), "f64": ("float64", "double")}


def emit(name: str):
    m = re.fullmatch(r"(f32|f64)-rvvsplit-by(\d+)gm(\d+)gp(\d+)((?:\+[\w=]+)*)", name)
    if not m:
        raise ValueError(f"bad variant {name!r}")
    dt_key, by, gm, gp, opts = m[1], int(m[2]), int(m[3]), int(m[4]), m[5].split("+")[1:]
    dtype, ctype = DTYPES[dt_key]
    cfg = ps.CreateKernelConfig(target=ps.Target.RISCV_RVV, default_dtype=dtype, ghost_layers=0)
    cfg.cpu.vectorize.enable = True
    cfg.cpu.vectorize.assume_inner_stride_one = True
    for o in opts:
        if o.startswith("pf="):
            cfg.cpu.vectorize.prefetch_distance = int(o.split("=")[1])
    lbm_config = LBMConfig(
        stencil=LBStencil(Stencil.D3Q19), method=Method.SRT, compressible=True, relaxation_rate=sp.Symbol("omega")
    )
    split = SplitAA(lbm_config, dtype, by, gm, gp, cfg)
    kernels = split.kernels()
    unique = SplitAA.unique_kernels(kernels)
    headers = set().union(*(k.required_headers for k in unique))
    codes = [k.get_c_code() for k in unique]
    decl, definition = split.driver_code("split_aa", ctype, kernels)
    output = "true" if "nomacro" not in opts else "false"
    header = f"// generated by misc/x60-lab/lab/gensplit.py: {name}"
    kernel_tu = "\n".join(
        [header, "#include <cstdint>", "#include <vector>"]
        + [f"#include {h}" for h in sorted(headers)]
        + ["#define RESTRICT __restrict__", "", *codes, "", definition, "",
           f'extern "C" void run_kernel_aa({ctype} * f, {ctype} * rho, {ctype} * u, int64_t n0, int64_t n1,',
           "    int64_t n2, int64_t sf1, int64_t sf2, int64_t sf3, int64_t sr1, int64_t sr2, int64_t su1,",
           f"    int64_t su2, int64_t su3, int parity, {ctype} omega)",
           "{",
           f"   split_aa(f, rho, u, n0, n1, n2, sf1, sf2, sf3, sr1, sr2, su1, su2, su3, parity != 0, {output}, omega);",
           "}", ""]
    )
    #   run.sh compiles a wrapper TU with the scalar flags; the driver is part of the kernel TU here
    wrapper_tu = f"{header} (wrapper: none needed)\n"
    return kernel_tu, wrapper_tu, len(kernels[0][True])


if __name__ == "__main__":
    out = pathlib.Path(sys.argv[1])
    for name in sys.argv[2:]:
        k, w, n = emit(name)
        (out / f"{name}.cpp").write_text(k)
        (out / f"{name}.wrap.cpp").write_text(w)
        print(f"wrote {name}: {n} passes per parity")
